import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from '../upstream/vscode/node_modules/playwright/index.mjs';
import { settingsFixture, settingsThemeCss } from './settings-ui-fixture.mjs';

const base = new URL('../extensions/studio-workstation/', import.meta.url);
const output = new URL('../.studio/settings-models-ui/', import.meta.url);
await mkdir(output, { recursive: true });
const [js, css, chinese, icons, font] = await Promise.all([
  readFile(new URL('dist/account-ui.js', base), 'utf8'), readFile(new URL('dist/account-ui.css', base), 'utf8'),
  readFile(new URL('l10n/bundle.l10n.zh-cn.json', base), 'utf8'),
  readFile(new URL('dist/codicons/codicon.css', base), 'utf8'), readFile(new URL('dist/codicons/codicon.ttf', base)),
]);
const iconCss = icons.replace(/url\([^)]+\)/g, `url(data:font/ttf;base64,${font.toString('base64')})`);
const browser = await chromium.launch({ channel: process.env.STEAMHARNESS_UI_BROWSER ?? 'chrome', headless: true });
const errors = [], checks = [];
try {
  for (const language of ['en', 'zh-cn']) for (const theme of ['light', 'dark', 'contrast']) for (const width of [1280, 640, 360]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } }); page.setDefaultTimeout(5000);
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html></html>' }));
    await page.goto('https://studio-settings.example.test');
    await page.setContent(`<!doctype html><html lang="${language}"><head><style>${settingsThemeCss(theme)}\n${iconCss}\n${css}</style></head><body><main id="account-app"></main><script id="studio-localization" type="application/json">${JSON.stringify({ locale: language, bundle: language === 'en' ? {} : JSON.parse(chinese) }).replaceAll('<', '\\u003c')}</script></body></html>`);
    await page.evaluate(() => { window.messages = []; window.acquireVsCodeApi = () => ({ postMessage: message => window.messages.push(message), setState: state => { window.savedState = state; } }); });
    await page.addScriptTag({ content: js });
    const send = data => page.evaluate(data => window.dispatchEvent(new MessageEvent('message', { data })), data);
    const last = () => page.evaluate(() => window.messages.filter(message => message.type === 'settings-models').at(-1));
    const zh = language === 'zh-cn';
    const pane = page.locator('#settings-models'), dialog = page.getByRole('dialog');
    const add = pane.getByRole('button', { name: zh ? '添加模型' : 'Add model', exact: true });
    const save = dialog.getByRole('button', { name: zh ? '保存' : 'Save', exact: true });
    const cancel = dialog.getByRole('button', { name: zh ? '取消' : 'Cancel', exact: true });
    const edit = row => row.getByRole('button', { name: zh ? '编辑' : 'Edit', exact: true });
    const choose = async (id, label) => {
      await page.locator(id).click();
      const menu = dialog.locator('.settings-dropdown-menu:popover-open');
      assert.equal(await menu.isVisible(), true, 'Dropdowns belong to the active modal and remain interactive');
      await menu.getByRole('option', { name: label, exact: true }).click();
    };
    const screenshot = async suffix => { if (theme !== 'contrast') await page.screenshot({ path: new URL(`${language}-${theme}-${width}-${suffix}.png`, output).pathname }); };
    await send({ type: 'settings', state: settingsFixture(language) });
    await send({ type: 'settings-models', state: { revision: 0, entries: [], systemAvailable: false } });
    await send({ type: 'settings-navigate', state: { section: 'models' } });
    assert.equal(await page.locator('#settings-title').textContent(), zh ? '模型' : 'Models');
    assert.equal(await pane.getByRole('table').count(), 0);
    await add.click();
    assert.equal(await dialog.isVisible(), true);
    assert.equal(await page.locator('#user-model-source').isVisible(), false, 'OSS does not offer a system AI source');
    assert.equal(await page.locator('#user-model-name').evaluate(input => document.activeElement === input), true);
    await page.locator('#settings-search').evaluate(input => input.focus());
    assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true, 'Background settings cannot receive focus');
    await cancel.focus(); await page.keyboard.press('Tab');
    assert.equal(await save.evaluate(button => document.activeElement === button), true);
    await page.locator('#user-model-apiKey').fill('discard-on-close');
    await page.keyboard.press('Escape');
    assert.equal(await dialog.count(), 0);
    assert.equal(await page.locator('#user-model-apiKey').inputValue(), '');
    assert.equal(await add.evaluate(button => document.activeElement === button), true);

    await add.click();
    await page.locator('#user-model-name').fill('My coding model');
    await choose('#user-model-apiKind', 'OpenAI Chat Completions');
    await page.locator('#user-model-baseUrl').fill('https://model.example.test/v1');
    await page.locator('#user-model-model').fill('coding-model');
    await screenshot('third-party-dialog');
    await page.locator('#user-model-apiKey').fill('ui-test-only-secret');
    await save.click();
    let saved = await last(); assert.equal(saved.model.source, 'third-party'); assert.equal(saved.model.apiKind, 'openai-completions');
    assert.equal(saved.model.apiKey, 'ui-test-only-secret'); assert.equal(await page.locator('#user-model-apiKey').inputValue(), '');
    assert.ok(!JSON.stringify(await page.evaluate(() => window.savedState)).includes('ui-test-only-secret'));
    assert.equal(await save.isDisabled(), true); assert.equal(await cancel.isDisabled(), true);
    await page.keyboard.press('Escape'); assert.equal(await dialog.isVisible(), true, 'Saving cannot be dismissed accidentally');
    await send({ type: 'settings-models-result', requestId: saved.requestId, message: 'Model endpoint unavailable' });
    assert.equal(await dialog.getByRole('alert').textContent(), 'Model endpoint unavailable');
    assert.equal(await page.locator('#user-model-name').inputValue(), 'My coding model');
    await page.locator('#user-model-apiKey').fill('ui-test-only-secret'); await save.click(); saved = await last();
    const { apiKey: _, ...entry } = saved.model;
    let state = { revision: 1, entries: [{ ...entry, hasApiKey: true }], systemAvailable: false };
    await send({ type: 'settings-models-result', requestId: saved.requestId, state });
    assert.equal(await dialog.count(), 0); assert.equal(await pane.getByRole('table').count(), 1);
    assert.equal(await pane.getByRole('columnheader').count(), 3);
    assert.deepEqual(await pane.getByRole('columnheader').allTextContents(), zh ? ['模型', '服务商', '操作'] : ['Model', 'Provider', 'Actions']);
    const firstRow = pane.locator(`[data-model-id="${entry.id}"]`);
    assert.ok((await firstRow.innerText()).includes(zh ? '默认模型' : 'Default model'));
    await edit(firstRow).click(); assert.equal(await page.locator('#user-model-apiKey').inputValue(), '');
    await send({ type: 'settings-models', state }); // Replacing rows must not break the dialog's return focus.
    await cancel.click(); assert.equal(await edit(firstRow).evaluate(button => document.activeElement === button), true);

    const builtins = Array.from({ length: 12 }, (_, index) => ({ id: `system-${index}`, source: 'system', credentialId: 'plan-one', model: `system-model-${index}`, name: `Built-in Model ${index}` }));
    state = { ...state, systemAvailable: true, entries: [...state.entries, ...builtins], providerNames: Object.fromEntries(builtins.map(model => [model.id, 'My AI account'])) };
    await send({ type: 'settings-models', state });
    const systemGroup = pane.locator('[data-model-group="system"]'), customGroup = pane.locator('[data-model-group="third-party"]');
    assert.deepEqual(await pane.locator('tbody').evaluateAll(groups => groups.map(group => group.dataset.modelGroup)), ['system', 'third-party']);
    assert.equal(await systemGroup.locator('[data-model-id]').count(), 12, 'All available built-in models appear without adding them');
    assert.equal(await systemGroup.getByRole('button', { name: zh ? '编辑' : 'Edit', exact: true }).count(), 0);
    assert.equal(await systemGroup.getByRole('button', { name: zh ? '删除' : 'Delete', exact: true }).count(), 0);
    assert.equal(await customGroup.locator('[data-model-id]').count(), 1);
    const groupToggle = systemGroup.locator('.settings-model-group button');
    await groupToggle.press('Enter'); assert.equal(await systemGroup.locator('[data-model-id]').count(), 0);
    assert.equal(await groupToggle.evaluate(button => document.activeElement === button), true);
    await page.locator('#settings-search').fill('Built-in Model 3');
    assert.equal(await pane.isVisible(), true, 'Search also finds models in collapsed groups');
    await page.locator('#settings-search').fill('');
    await groupToggle.focus();
    await send({ type: 'settings-models', state });
    assert.equal(await groupToggle.evaluate(button => document.activeElement === button), true, 'Host updates preserve the focused group toggle');
    await groupToggle.press('Enter'); assert.equal(await systemGroup.locator('[data-model-id]').count(), 12);
    const refresh = pane.getByRole('button', { name: zh ? '刷新内置可用模型' : 'Refresh built-in models', exact: true });
    await refresh.click(); const request = await last(); assert.equal(request.action, 'catalog');
    assert.equal(await refresh.isDisabled(), true);
    await send({ type: 'settings-models', state: { ...state, catalogLoading: true } });
    assert.equal(await systemGroup.locator('[data-model-id]').count(), 12, 'Refreshing retains the existing catalogue');
    await send({ type: 'settings-model-catalog', requestId: 'obsolete', catalog: { entries: [] } });
    assert.equal(await refresh.isDisabled(), true, 'An obsolete reply cannot finish the active refresh');
    await send({ type: 'settings-model-catalog', requestId: request.requestId, message: 'Catalogue offline', state: { ...state, catalogLoading: false, catalogError: 'Catalogue offline' } });
    assert.equal(await systemGroup.locator('[data-model-id]').count(), 12);
    assert.ok((await pane.innerText()).includes('Catalogue offline'));
    await refresh.click(); const retry = await last(); assert.notEqual(retry.requestId, request.requestId);
    builtins[0] = { ...builtins[0], name: 'Updated built-in model' };
    state = { ...state, entries: [state.entries[0], ...builtins] };
    await send({ type: 'settings-models', state });
    await send({ type: 'settings-model-catalog', requestId: retry.requestId, catalog: { entries: [] } });
    assert.equal(await refresh.isDisabled(), false);
    assert.ok(!(await pane.innerText()).includes('Catalogue offline'));
    const systemRow = pane.locator('[data-model-id="system-0"]');
    assert.ok((await systemRow.innerText()).includes('Updated built-in model'));
    await systemRow.getByRole('button', { name: zh ? '设为默认' : 'Set as default', exact: true }).click();
    const preference = await last(); assert.equal(preference.action, 'default'); assert.equal(preference.id, 'system-0');
    state = { ...state, revision: 2, entries: [builtins[0], state.entries[0], ...builtins.slice(1)] };
    await send({ type: 'settings-models-result', requestId: preference.requestId, state });
    assert.ok((await systemRow.innerText()).includes(zh ? '默认模型' : 'Default model'));
    await page.locator('#settings-search').fill('Updated built-in model'); assert.equal(await pane.isVisible(), true);
    await page.locator('#settings-search').fill('');
    const long = { ...state.entries[1], id: 'long-model', name: 'A long model name for documentation, coding and project planning', model: 'provider/long-model-identifier-for-project-planning', baseUrl: 'https://long-provider-endpoint.example.test/compatible/api/v1' };
    state = { ...state, entries: [...state.entries, long] }; await send({ type: 'settings-models', state });
    await screenshot('table');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Only the table scrolls horizontally');
    const viewport = pane.getByRole('region', { name: zh ? '我的模型' : 'Your models' });
    assert.equal(await viewport.evaluate(element => element.getBoundingClientRect().right <= innerWidth), true);
    if (width === 360) assert.equal(await viewport.evaluate(element => element.scrollWidth > element.clientWidth), true);
    await viewport.evaluate(element => { element.scrollLeft = element.scrollWidth; });
    const remove = pane.locator('[data-model-id="long-model"]').getByRole('button', { name: zh ? '删除' : 'Delete', exact: true });
    const beforeDelete = (await last()).requestId; await remove.click(); assert.equal((await last()).requestId, beforeDelete);
    await pane.locator('[data-model-id="long-model"]').getByRole('button', { name: zh ? '确认删除' : 'Confirm delete', exact: true }).click();
    const deleted = await last(); assert.equal(deleted.action, 'delete');
    state = { ...state, revision: 5, entries: state.entries.filter(model => model.id !== long.id) };
    await send({ type: 'settings-models-result', requestId: deleted.requestId, state });

    await page.setViewportSize({ width, height: 360 });
    await add.click();
    await page.locator('#user-model-apiKey').fill('short-window-secret');
    assert.equal(await dialog.locator('.settings-model-fields').evaluate(element => element.scrollHeight > element.clientHeight), true);
    const footer = await dialog.locator('footer').boundingBox(), box = await dialog.boundingBox();
    assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= 360);
    assert.ok(footer.y + footer.height <= 360 && footer.y >= box.y, 'Actions remain visible when the fields scroll');
    await screenshot('short-dialog');
    await page.locator('#user-model-apiKind').click(); await page.keyboard.press('Escape');
    assert.equal(await dialog.isVisible(), true, 'Escape closes the dropdown before the dialog');
    assert.equal(await dialog.locator('.settings-dropdown-menu:popover-open').count(), 0);
    await page.keyboard.press('Escape'); assert.equal(await dialog.count(), 0);
    assert.equal(await page.locator('#user-model-apiKey').inputValue(), '');
    await page.setViewportSize({ width, height: 900 });
    await add.click(); await send({ type: 'settings-navigate', state: { section: 'general' } });
    assert.equal(await dialog.count(), 0, 'Host navigation never leaves an orphaned modal');
    checks.push(`${language}/${theme}/${width}: modal focus, cancel, save errors, secrets, automatic built-ins, refresh races, grouped table actions, search and short-window scrolling`);
    await page.close();
  }
  assert.deepEqual(errors, []); console.log(JSON.stringify({ checks, errors, screenshots: output.pathname }, null, 2));
} finally { await browser.close(); }
