import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { prepareRelease } from '../prepare-release.mjs';
import { writeReleaseFixture } from '../../../docs/scripts/__tests__/release-fixture.mjs';

test('prepares only the selected unit after checking its exact bilingual pages', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'steamharness-server-release-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const docsRoot = path.join(root, 'docs');
  await mkdir(path.join(root, 'web'));
  const webManifest = path.join(root, 'web/package.json');
  const serverManifest = path.join(root, 'package.json');
  const previous = '{"version":"1.0.0"}\n';
  await Promise.all([writeFile(webManifest, previous), writeFile(serverManifest, previous)]);
  const options = { root, docsRoot, version: '1.1.0' };
  await assert.rejects(prepareRelease({ ...options, unit: 'unknown' }), /Unsupported release unit/u);
  await assert.rejects(prepareRelease({ ...options, unit: 'server', version: '0.9.0' }), /must not be lower/u);
  await assert.rejects(prepareRelease({ ...options, unit: 'server-web' }), /Missing release notes/u);
  await writeReleaseFixture(docsRoot, 'server-web', '1.1.0', { enId: 'another-entry' });
  await assert.rejects(prepareRelease({ ...options, unit: 'server-web' }), /note IDs\/sections differ/u);
  assert.equal(await readFile(webManifest, 'utf8'), previous);
  await writeReleaseFixture(docsRoot, 'server', '1.1.0');
  const result = await prepareRelease({ ...options, unit: 'server' });
  assert.equal(result.tag, 'server/v1.1.0');
  assert.equal(result.docsPaths.en, '/en/guides/releases/server/v1.1.0/');
  assert.equal(JSON.parse(await readFile(serverManifest, 'utf8')).version, '1.1.0');
  assert.equal(await readFile(webManifest, 'utf8'), previous);
  assert.deepEqual(await prepareRelease({ ...options, unit: 'server' }), result);
});
